using UnityEngine;

namespace Redline.Game.Ronin
{
    /// <summary>Animation slots of the Tech Ronin, in the order of <see cref="RoninAssets.Clips"/>.</summary>
    public enum RoninClip
    {
        Idle, Run, SlideAttack, Jump, Fall, JumpAttack, Attack1, Attack2, Attack3, SpinAttack, Hurt, Death, Hang,
        /// <summary>Long-stride run (v3).</summary>
        Sprint,
        /// <summary>Touchdown squash after a fast fall (v3).</summary>
        Land,
        /// <summary>Slashes over the run legs (v3).</summary>
        RunAttack1, RunAttack2
    }

    /// <summary>
    /// Build-safe bundle of everything <see cref="RoninView"/> needs: the imported model, the clips (indexed by
    /// <see cref="RoninClip"/>) and the URP materials that replace the FBX's embedded ones by name.
    /// The instance lives at <c>Assets/Art3D/Ronin/Resources/Ronin/RoninAssets.asset</c> (generated by
    /// <c>Redline.RoninEditor.RoninSetup.EnsureAssets</c>), so a built game loads it with <see cref="Load"/>.
    /// </summary>
    [CreateAssetMenu(menuName = "Redline/Ronin Assets", fileName = "RoninAssets")]
    public sealed class RoninAssets : ScriptableObject
    {
        /// <summary>Resources path of the generated asset.</summary>
        public const string ResourcePath = "Ronin/RoninAssets";

        /// <summary>The character model (ronin.fbx, Humanoid).</summary>
        public GameObject Model;
        /// <summary>Clips indexed by <see cref="RoninClip"/>.</summary>
        public AnimationClip[] Clips = new AnimationClip[17];
        /// <summary>URP materials; a renderer slot whose material name matches one of these is replaced.</summary>
        public Material[] Materials;
        /// <summary>Default tier colour (HDR) for the hat brim and blade emissive.</summary>
        [ColorUsage(false, true)] public Color DefaultTier = new Color(0.4f, 2.5f, 3f);

        /// <summary>Loads the generated asset from Resources (works in built players). Null if missing.</summary>
        public static RoninAssets Load() => Resources.Load<RoninAssets>(ResourcePath);
    }
}
